const groups: Record<ShortcutCategory, Row[]> = {
  windows,
  windowsManagement,
  capture,
  accessibility,
  explorer,
  browser,
  textEditing,
  office,
  excel,
  outlook,
  vscode,
  devtools,
  terminal,
};

const levels: Record<1 | 2 | 3, Difficulty> = {
  1: "starter",
  2: "steady",
  3: "stretch",
};

const parseChord = (chord: string) =>
  chord
    .trim()
    .split(/(?<=.)\+/)
    .map((key) => key.trim());

export const shortcuts: Shortcut[] = Object.entries(groups).flatMap(
  ([category, rows]) =>
    rows.map(([id, action, chords, level, tip]) => {
      const [expected, ...alternates] = chords.split(" | ").map(parseChord);
      return {
        id,
        action,
        expected,
        ...(alternates.length ? { alternates } : {}),
        category: category as ShortcutCategory,
        difficulty: levels[level],
        ...(tip ? { tip } : {}),
      };
    }),
);
